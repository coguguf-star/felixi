local function char()
    local c = plr.Character
    if not c then return nil end
    local h = c:FindFirstChildOfClass("Humanoid")
    local r = c:FindFirstChild("HumanoidRootPart")
    if not h or not r then return nil end
    return c, h, r
end

local function nearestIndex(pos)
    local best, bd = 1, math.huge
    for i = 1, #PATH do
        local d = (PATH[i] - pos).Magnitude
        if d < bd then best, bd = i, d end
    end
    return best, bd
end

local CHAIR_IDX     = nearestIndex(CHAIR)
local CAMP2_IDX     = nearestIndex(CAMP2)
local CAMP_LAST_IDX = nearestIndex(CAMP_LAST)

local function moveTo(dest)
    local _, _, r = char()
    if not r then return end
    local from = r.Position
    local dist = (dest - from).Magnitude
    local steps = math.max(1, math.ceil(dist / STEP_SIZE))
    for s = 1, steps do
        if not running then return end
        local _, _, rr = char()
        if not rr then return end
        rr.AssemblyLinearVelocity  = Vector3.zero
        rr.AssemblyAngularVelocity = Vector3.zero
        rr.CFrame = CFrame.new(from:Lerp(dest, s / steps))
        task.wait(STEP_DELAY)
    end
end

