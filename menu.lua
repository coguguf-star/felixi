local function doRespawn()
    local c, h = char()
    if h then pcall(function() h.Health = 0 end) end
    task.wait(0.4)
    if c and c.Parent and h and h.Health > 0 then
        pcall(function() c:BreakJoints() end)
    end
end

local function waitChar(timeout)
    local t = 0
    while t < (timeout or 15) do
        local c = plr.Character
        if c and c:FindFirstChild("HumanoidRootPart") and c ~= lastChar then return c end
        task.wait(0.25); t = t + 0.25
    end
    return plr.Character
end

local function runOnce(dest)
    local c, h, r = char()
    if not r then return end

    local start, dist = nearestIndex(r.Position)
    if dist > 120 then start = 1 end
    -- kalau destinasi lebih belakang dari titik terdekat, mulai dari terdekat
    if start > dest then start = 1 end
    idx = start
    log("mulai dari titik " .. idx .. "/" .. dest)

    local nextLog = idx
    while running and idx <= dest do
        if SIT_ON and idx == CHAIR_IDX then
            moveTo(PATH[idx])
            task.wait(0.3)
            doSit()
            task.wait(0.4)
        else
            moveTo(PATH[idx])
        end

        idx = idx + 1
        if idx >= nextLog then
            local _, _, rr = char()
            statusLbl.Text = string.format("STATUS: titik %d/%d | Y %.0f", idx, dest, rr and rr.Position.Y or 0)
            nextLog = idx + 25
        end
    end
end

local function mainLoop()
    while running do
        local tripsBefore = readTrips()
        log("trip awal: " .. tostring(tripsBefore))

        local ok, err = pcall(function() runOnce(destIndex) end)
        if not ok then log("ERR: " .. tostring(err)) end
        if not running then break end

        -- kalau full trip, tunggu konfirmasi trip naik
        if destIndex >= #PATH then
            log("nyampe dasar, cek trip...")
            local naik = false
            for _ = 1, 30 do
                local now = readTrips()
                if tripsBefore and now and now > tripsBefore then naik = true; break end
                task.wait(0.5)
            end
            if not tripsBefore then
                local _, _, rr = char()
                if rr and rr.Position.Y <= BOTTOM_Y then naik = true end
                log("(counter ga kedeteksi, pakai cek kedalaman)")
            end
            statusLbl.Text = naik and "STATUS: TRIP BERTAMBAH" or "STATUS: trip belum kebaca"
            log(naik and "TRIP BERTAMBAH" or "trip belum kebaca")
        end

        if not LOOP_ON then
            running = false
            log("selesai (loop off)")
            break
        end

        log("respawn...")
        lastChar = plr.Character
        doRespawn()
        waitChar(12)
        local jeda = math.random(3, 8)
        log("tunggu " .. jeda .. "s buat load world")
        task.wait(jeda)
        log("restart dari awal")
    end
    statusLbl.Text = "STATUS: berhenti"
end

