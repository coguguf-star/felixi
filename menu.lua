local function scanTrip()
    for name, val in pairs(plr:GetAttributes()) do
        if type(val) == "number" and string.lower(name):find("trip") then
            tripRef = { kind = "attr", name = name }
            return tripRef
        end
    end
    local function scan(root, depth)
        if depth > 4 then return nil end
        for _, v in ipairs(root:GetChildren()) do
            if v:IsA("ValueBase") and string.lower(v.Name):find("trip") then return v end
            if v:IsA("Folder") or v:IsA("Configuration") or v:IsA("Model") then
                local r = scan(v, depth + 1)
                if r then return r end
            end
        end
        return nil
    end
    local v = scan(plr, 0) or scan(game:GetService("ReplicatedStorage"), 0)
    if v then tripRef = { kind = "obj", obj = v } end
    return tripRef
end

local function readTrips()
    if not tripRef then scanTrip() end
    if not tripRef then return nil end
    if tripRef.kind == "attr" then
        local ok, v = pcall(function() return plr:GetAttribute(tripRef.name) end)
        return ok and tonumber(v) or nil
    end
    if not tripRef.obj or not tripRef.obj.Parent then tripRef = nil; return nil end
    local ok, v = pcall(function() return tripRef.obj.Value end)
    return ok and tonumber(v) or nil
end

local function dumpStats()
    log("--- CEK STATS ---")
    for name, val in pairs(plr:GetAttributes()) do
        log("attr: " .. name .. " = " .. tostring(val))
    end
    for _, v in ipairs(plr:GetDescendants()) do
        if v:IsA("ValueBase") then log("val: " .. v:GetFullName() .. " = " .. tostring(v.Value)) end
    end
    for _, v in ipairs(game:GetService("ReplicatedStorage"):GetDescendants()) do
        if v:IsA("ValueBase") and string.lower(v.Name):find("trip") then
            log("RS: " .. v:GetFullName() .. " = " .. tostring(v.Value))
        end
    end
    local t = readTrips()
    log("trip terbaca: " .. tostring(t))
    log("--- SELESAI ---")
end

