local function findSeatNear(pos, radius)
    local params = OverlapParams.new()
    params.FilterDescendantsInstances = {plr.Character}
    local ok, parts = pcall(function() return workspace:GetPartBoundsInRadius(pos, radius, params) end)
    if not ok or not parts then return nil end
    local best, bd = nil, radius
    for _, p in ipairs(parts) do
        if p:IsA("Seat") or p:IsA("VehicleSeat") then
            local d = (p.Position - pos).Magnitude
            if d < bd then best, bd = p, d end
        end
    end
    return best
end

local function tryPrompt(pos, radius)
    local hit = false
    for _, d in ipairs(workspace:GetDescendants()) do
        if d:IsA("ProximityPrompt") and d.Enabled then
            local par = d.Parent
            if par and par:IsA("BasePart") then
                local ok, dist = pcall(function() return (par.Position - pos).Magnitude end)
                if ok and dist < radius then
                    pcall(function() d:InputHoldBegin() end)
                    task.wait(0.5)
                    pcall(function() d:InputHoldEnd() end)
                    hit = true
                end
            end
        end
    end
    return hit
end

local function doSit()
    local _, h, r = char()
    if not h or not r then return false end

    local seat = findSeatNear(CHAIR, 45) or findSeatNear(r.Position, 45)

    if seat then
        log("kursi ketemu: " .. seat.Name)
        local top = seat.Position + Vector3.new(0, seat.Size.Y / 2 + 2.5, 0)
        pcall(function() r.CFrame = CFrame.new(top) end)
        task.wait(0.35)
        pcall(function() seat:Sit(h) end)
    else
        log("kursi ga ketemu, coba prompt...")
        tryPrompt(CHAIR, 25)
        task.wait(0.3)
        if not h.Sit then pcall(function() h.Sit = true end) end
    end

    for _ = 1, 40 do
        if h.Sit then
            log("DUDUK terkonfirmasi")
            if h.SeatPart then
                h.Sit = false
                task.wait(0.15)
                h.Sit = true
                log("weld dilepas, tetap duduk")
            end
            return true
        end
        task.wait(0.1)
    end
    log("GAGAL duduk - lanjut aja")
    return false
end

